export function createPreviewWeather(config, overrides = {}) {
  const baseTemperature = Math.round(
    (config.temperatureRange[0] + config.temperatureRange[1]) / 2,
  )
  return {
    ...config,
    temperature: overrides.temperature ?? baseTemperature,
    feelsLike:
      (overrides.temperature ?? baseTemperature) -
      (config.windSpeed > 35 ? 3 : 1),
    windSpeed: overrides.windSpeed ?? config.windSpeed,
    particleIntensity: overrides.intensity ?? config.particleIntensity,
    simulated: true,
  }
}
